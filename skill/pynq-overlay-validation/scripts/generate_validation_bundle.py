def safe_name(value: str) -> str:
    result = re.sub(r"[^A-Za-z0-9_.-]+", "_", value).strip("._")
    return result or "pynq_overlay"


def main() -> None:
    parser = argparse.ArgumentParser(description="Generate a portable PYNQ overlay validation bundle")
    parser.add_argument("--hwh", type=Path, required=True)
    parser.add_argument("--bit", type=Path, required=True)
    parser.add_argument("--output-dir", type=Path, required=True)
    parser.add_argument("--project-name")
    args = parser.parse_args()
    inventory = inspect_hwh(args.hwh, args.bit)
    output = args.output_dir.resolve()
    if output.exists() and any(output.iterdir()):
        raise FileExistsError("output-dir must be empty")
    overlay_dir = output / "overlay"
    vectors_dir = output / "vectors"
    overlay_dir.mkdir(parents=True, exist_ok=True)
    vectors_dir.mkdir(parents=True, exist_ok=True)
    design_name = safe_name(args.project_name or inventory.get("system", {}).get("NAME", "overlay"))
    target_bit = overlay_dir / f"{design_name}.bit"
    target_hwh = overlay_dir / f"{design_name}.hwh"
    shutil.copy2(args.bit, target_bit)
    shutil.copy2(args.hwh, target_hwh)
    required = []
    by_name = {value["instance"]: value for value in inventory["modules"]}
    addressable = [item["instance"] for item in inventory["address_ranges"]
                   if item.get("memory_type") == "REGISTER"]
    interesting = list(dict.fromkeys(inventory["dma_candidates"] + addressable))
    for name in interesting:
        module = by_name[name]
        required.append({
            "pattern": f"^{re.escape(name)}$",
            "expected_type_pattern": re.escape(str(module.get("vlnv") or module.get("modtype") or "")),
            "minimum_matches": 1,
        })
    dma_ip = inventory["dma_candidates"][0] if len(inventory["dma_candidates"]) == 1 else None
    contract = {
        "schema": "pynq-overlay-validation-contract-v1",
        "project": design_name,
        "overlay": {
            "bit": target_bit.relative_to(output).as_posix(),
            "hwh": target_hwh.relative_to(output).as_posix(),
            "bit_sha256": inventory["bit"]["sha256"],
            "hwh_sha256": inventory["hwh"]["sha256"],
            "download": True,
        },
        "required_ip": required,
        "register_checks": [],
        "adapter": "adapter.py",
        "adapter_config": {"dma_ip": dma_ip},
        "test": {
            "input_npz": "vectors/input.npz",
            "golden_npz": "vectors/golden.npz",
            "warmup": 2,
            "repeats": 10,
            "timeout_seconds": 30.0,
            "comparison": {"exact": False, "rtol": 1e-5, "atol": 1e-7},
        },
    }
    (output / "overlay_validation.json").write_text(
        json.dumps(contract, ensure_ascii=False, indent=2) + "\n", encoding="utf-8")
    (output / "hwh_inventory.json").write_text(
        json.dumps(inventory, ensure_ascii=False, indent=2) + "\n", encoding="utf-8")
    (output / "adapter.py").write_text(ADAPTER, encoding="utf-8")
    (output / "README.md").write_text(BUNDLE_README, encoding="utf-8")
    (vectors_dir / "README.md").write_text(
        "Create input.npz and golden.npz with NumPy. Golden keys must match adapter outputs.\n",
        encoding="utf-8")
    print(json.dumps({"status": "PASS", "output": str(output),
                      "required_ip": required, "dma_ip": dma_ip}, ensure_ascii=False, indent=2))


if __name__ == "__main__":
    main()
